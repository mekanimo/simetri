"""Compile public ``sg.*`` names into help topic listings.

Run before a release (or when exports change):

    uv run python -m simetri.helpers.compile_help_topics

Writes ``help_topics_generated.py`` next to this module.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable


def topic_query_tokens(query: str) -> set[str]:
    """Tokens used to match top-level ``sg`` names to a help topic key."""
    from .help_utils import normalize

    query_normalized = normalize(query)
    tokens: set[str] = set()
    if not query_normalized:
        return tokens

    for part in query_normalized.replace("-", "_").split("_"):
        if part:
            tokens.add(part)
    tokens.add(query_normalized)
    if query_normalized.endswith("s") and len(query_normalized) > 3:
        if not query_normalized.endswith("ss"):
            tokens.add(query_normalized[:-1])
    elif not query_normalized.endswith("s"):
        tokens.add(query_normalized + "s")
    return tokens


def _sg_names_for_topic(topic: str, public_names: Iterable[str]) -> tuple[str, ...]:
    from .help_utils import _help_name_tokens

    tokens = topic_query_tokens(topic)
    matches = [
        f"sg.{name}"
        for name in public_names
        if tokens.intersection(_help_name_tokens(name))
    ]
    return tuple(sorted(set(matches), key=str.casefold))


def _compiled_topic_aliases(topic_keys: Iterable[str]) -> dict[str, str]:
    aliases: dict[str, str] = {}
    keys = set(topic_keys)
    for topic in sorted(keys):
        if not topic.endswith("s") or len(topic) <= 3 or topic.endswith("ss"):
            continue
        singular = topic[:-1]
        if singular not in keys:
            aliases[singular] = topic
    return aliases


def compile_help_topics() -> tuple[dict[str, tuple[str, ...]], dict[str, str]]:
    """Return compiled topic entries and singular topic aliases."""
    import simetri.graphics as sg  # noqa: F401

    from .help_utils import _public_sg_names, all_help_topic_keys
    from .help_visibility import filter_sg_export_names

    topic_keys = sorted(all_help_topic_keys())
    public_names = filter_sg_export_names(_public_sg_names())
    compiled = {
        topic: _sg_names_for_topic(topic, public_names) for topic in topic_keys
    }
    aliases = _compiled_topic_aliases(topic_keys)
    return compiled, aliases


def _format_generated_module(
    compiled: dict[str, tuple[str, ...]],
    aliases: dict[str, str],
    doc_placeholders: dict[str, tuple[str, ...]],
) -> str:
    lines = [
        '"""Auto-generated by ``python -m simetri.helpers.compile_help_topics``.',
        "",
        "Do not edit by hand. Re-run the compiler before release when ``sg``",
        "exports change.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "COMPILED_SG_BY_TOPIC: dict[str, tuple[str, ...]] = {",
    ]
    for topic in sorted(compiled):
        entries = compiled[topic]
        lines.append(f"    {topic!r}: (")
        for entry in entries:
            lines.append(f"        {entry!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    lines.append("COMPILED_TOPIC_ALIASES: dict[str, str] = {")
    for key in sorted(aliases):
        lines.append(f"    {key!r}: {aliases[key]!r},")
    lines.append("}")
    lines.append("")
    lines.append("COMPILED_DOC_PLACEHOLDERS_BY_TOPIC: dict[str, tuple[str, ...]] = {")
    for topic in sorted(doc_placeholders):
        entries = doc_placeholders[topic]
        lines.append(f"    {topic!r}: (")
        for entry in entries:
            lines.append(f"        {entry!r},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _validate_supplements(topic_keys: set[str]) -> None:
    from .help_doc_placeholders import parse_doc_placeholders
    from .help_topic_supplements import (
        RELATED_TOPICS,
        SG_NAME_TO_TOPICS,
        TOPIC_ALIASES,
        TOPIC_DOC_PLACEHOLDERS,
        TOPIC_SG_ENTRIES,
    )

    for topic in TOPIC_SG_ENTRIES:
        if topic not in topic_keys:
            print(f"warning: TOPIC_SG_ENTRIES unknown topic {topic!r}")
    for export_name, topics in SG_NAME_TO_TOPICS.items():
        for topic in topics:
            if topic not in topic_keys:
                print(
                    f"warning: SG_NAME_TO_TOPICS[{export_name!r}] "
                    f"unknown topic {topic!r}"
                )
    for alias, topic in TOPIC_ALIASES.items():
        if topic not in topic_keys:
            print(f"warning: TOPIC_ALIASES[{alias!r}] unknown topic {topic!r}")
    for topic in RELATED_TOPICS:
        if topic not in topic_keys:
            print(f"warning: RELATED_TOPICS unknown topic {topic!r}")
        for related in RELATED_TOPICS[topic]:
            if related not in topic_keys:
                print(
                    f"warning: RELATED_TOPICS[{topic!r}] "
                    f"unknown related topic {related!r}"
                )
    for topic, placeholders in TOPIC_DOC_PLACEHOLDERS.items():
        if topic not in topic_keys:
            print(f"warning: TOPIC_DOC_PLACEHOLDERS unknown topic {topic!r}")
        for placeholder in placeholders:
            if not parse_doc_placeholders(placeholder):
                print(
                    f"warning: TOPIC_DOC_PLACEHOLDERS[{topic!r}] "
                    f"invalid placeholder {placeholder!r}"
                )


def main() -> None:
    from .check_help_visibility import main as report_visibility
    from .compile_help_doc_refs import compile_doc_placeholders
    from .help_utils import _TOPIC_GUIDES_DIR, all_help_topic_keys

    report_visibility()
    print("")
    compiled, aliases = compile_help_topics()
    topic_keys = set(all_help_topic_keys())
    _validate_supplements(topic_keys)
    doc_placeholders = compile_doc_placeholders(
        _TOPIC_GUIDES_DIR,
        topic_keys,
        compiled,
        api_docs_dir=Path(__file__).resolve().parents[1] / "docs",
    )
    target = Path(__file__).with_name("help_topics_generated.py")
    target.write_text(
        _format_generated_module(compiled, aliases, doc_placeholders),
        encoding="utf-8",
    )
    print(
        f"Wrote {target} ({len(compiled)} topics, {len(aliases)} aliases, "
        f"{len(doc_placeholders)} topics with doc placeholders)"
    )


if __name__ == "__main__":
    main()
